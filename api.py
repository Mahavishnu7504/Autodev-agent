@app.post("/run-task")
def run_task(
    request: TaskRequest,
):

    start_time = time.perf_counter()

    clear_logs()

    plan = None
    result = None
    task_id = None

    try:

        log(
            "🧠 AutoDev task received."
        )

        log(
            f"📌 Task: {request.task}"
        )

        # ----------------------------------------------------
        # PHASE 1: PLANNING
        # ----------------------------------------------------

        plan = create_plan(
            request.task,
            request.inputs,
        )

        # ----------------------------------------------------
        # PHASE 2+:
        # TEST GENERATION
        # EXECUTION
        # AUTONOMOUS REPAIR
        # ----------------------------------------------------

        result = execute_plan(
            plan=plan,
            inputs=request.inputs,
            task=request.task,
        )

        duration = (
            time.perf_counter()
            - start_time
        )

        status = (
            "success"
            if result.get("success")
            else "error"
        )

        workspace_name = result.get(
            "workspace_name"
        )

        zip_file = result.get(
            "zip_file"
        )

        zip_url = (
            f"/download-project/"
            f"{workspace_name}"
            if (
                workspace_name
                and zip_file
            )
            else None
        )

        project_url = (
            f"/projects/"
            f"{workspace_name}"
            if workspace_name
            else None
        )

        # ----------------------------------------------------
        # HISTORY
        # ----------------------------------------------------

        if create_task_record:

            try:

                history_record = (
                    create_task_record(
                        task=request.task,
                        status=status,
                        plan=plan,
                        logs=get_logs(),
                        result=result,
                        generated_file=workspace_name,
                        duration_seconds=duration,
                        inputs=request.inputs,
                    )
                )

                task_id = (
                    history_record.get(
                        "id"
                    )
                )

            except Exception as exc:

                log(
                    f"⚠️ History save failed: "
                    f"{exc}"
                )

        # ----------------------------------------------------
        # RESPONSE
        # ----------------------------------------------------

        return {

            "status": status,

            "task": request.task,

            "task_id": task_id,

            "plan": plan,

            "logs": get_logs(),

            "project_name": result.get(
                "project_name"
            ),

            "workspace_name": workspace_name,

            "project_url": project_url,

            "zip_url": zip_url,

            "result": result,

            "duration_seconds": round(
                duration,
                3,
            ),
        }

    except Exception as exc:

        duration = (
            time.perf_counter()
            - start_time
        )

        error_message = str(exc)

        log(
            f"❌ Agent error: "
            f"{error_message}"
        )

        # ----------------------------------------------------
        # ERROR HISTORY
        # ----------------------------------------------------

        if create_task_record:

            try:

                history_record = (
                    create_task_record(
                        task=request.task,
                        status="error",
                        plan=plan,
                        logs=get_logs(),
                        result={
                            "success": False,
                            "error": error_message,
                        },
                        generated_file=None,
                        duration_seconds=duration,
                        inputs=request.inputs,
                    )
                )

                task_id = (
                    history_record.get(
                        "id"
                    )
                )

            except Exception:
                pass

        return {

            "status": "error",

            "task": request.task,

            "task_id": task_id,

            "message": error_message,

            "logs": get_logs(),

            "duration_seconds": round(
                duration,
                3,
            ),
        }


