@app.get(
    "/projects/{workspace_name}"
)
def project_details(
    workspace_name: str,
):

    workspace = (
        resolve_project_workspace(
            workspace_name
        )
    )

    if workspace is None:

        raise HTTPException(
            status_code=404,
            detail="Project not found.",
        )

    files = []

    for path in sorted(
        workspace.rglob("*")
    ):

        if not path.is_file():
            continue

        relative_path = (
            path.relative_to(
                workspace
            )
        )

        # ----------------------------------------------------
        # HIDE CACHE / BINARY FILES
        # ----------------------------------------------------

        if not is_displayable_project_file(
            relative_path
        ):
            continue

        relative = (
            relative_path.as_posix()
        )

        files.append({

            "path": relative,

            "view_url": (
                f"/projects/"
                f"{workspace_name}"
                f"/file/"
                f"{relative}"
            ),
        })

    zip_path = (
        PROJECTS_DIR
        / f"{workspace_name}.zip"
    )

    return {

        "workspace_name":
            workspace_name,

        "project_name": re.sub(
            r"\_[0-9a-f]{8}$",
            "",
            workspace_name,
        ),

        "files": files,

        "zip_available":
            zip_path.exists(),

        "zip_url": (
            f"/download-project/"
            f"{workspace_name}"
            if zip_path.exists()
            else None
        ),
    }


