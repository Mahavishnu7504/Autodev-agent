# ============================================================
# PROJECT FILE FILTERING
# ============================================================

# These directories are generated by Python, package managers,
# IDEs, Git, or development tooling. They should NOT appear in
# the AutoDev project browser.

IGNORED_PROJECT_DIRS = {
    ".git",
    ".github",
    "__pycache__",
    ".pytest_cache",
    ".mypy_cache",
    ".ruff_cache",
    ".tox",
    ".coverage",
    ".idea",
    ".vscode",
    ".venv",
    "venv",
    "env",
    "node_modules",
}


# Binary/generated Python artifacts.

IGNORED_PROJECT_SUFFIXES = {
    ".pyc",
    ".pyo",
    ".pyd",
}


IGNORED_PROJECT_FILES = {
    ".DS_Store",
    "Thumbs.db",
}


def is_displayable_project_file(
    path: Path,
) -> bool:
    """
    Determine whether a project file should be visible
    in the AutoDev dashboard.

    This prevents binary/cache artifacts such as:

        __pycache__/main.cpython-314.pyc

    from being displayed as source code.
    """

    if path.name in IGNORED_PROJECT_FILES:
        return False

    if path.suffix.lower() in IGNORED_PROJECT_SUFFIXES:
        return False

    if any(
        part in IGNORED_PROJECT_DIRS
        for part in path.parts
    ):
        return False

    return True


# ============================================================
# PROJECT NAME
# ============================================================

def safe_project_name(
    value: str,
) -> str:

    cleaned = re.sub(
        r"[^A-Za-z0-9\_-]+",
        "_",
        str(
            value
            or "AutoDev_Project"
        ),
    ).strip("_")

    return (
        cleaned[:80]
        or "AutoDev_Project"
    )


# ============================================================
# PROJECT WORKSPACE RESOLUTION
# ============================================================

def resolve_project_workspace(
    workspace_name: str,
) -> Path | None:

    if not workspace_name:
        return None

    safe_name = Path(
        workspace_name
    ).name

    if safe_name != workspace_name:
        return None

    path = PROJECTS_DIR / safe_name

    if (
        not path.exists()
        or not path.is_dir()
    ):
        return None

    return path


# ============================================================
# PROJECT ZIP RESOLUTION
# ============================================================

def resolve_project_zip(
    workspace_name: str,
) -> Path | None:

    if not workspace_name:
        return None

    safe_name = Path(
        workspace_name
    ).name

    if safe_name != workspace_name:
        return None

    path = (
        PROJECTS_DIR
        / f"{safe_name}.zip"
    )

    if (
        not path.exists()
        or not path.is_file()
    ):
        return None

    return path


# ============================================================
# PROJECT FILE RESOLUTION
# ============================================================

def resolve_project_file(
    workspace_name: str,
    file_path: str,
) -> Path | None:

    workspace = resolve_project_workspace(
        workspace_name
    )

    if workspace is None:
        return None

    normalized = (
        str(file_path)
        .replace("\\", "/")
        .lstrip("/")
    )

    if not normalized:
        return None

    candidate = (
        workspace / normalized
    ).resolve()

    try:

        candidate.relative_to(
            workspace.resolve()
        )

    except ValueError:

        return None

    if (
        not candidate.exists()
        or not candidate.is_file()
    ):
        return None

    # Never expose generated/binary artifacts.
    relative = candidate.relative_to(
        workspace
    )

    if not is_displayable_project_file(
        relative
    ):
        return None

    return candidate


