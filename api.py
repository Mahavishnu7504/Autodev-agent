@app.get("/projects")
def list_projects():

    PROJECTS_DIR.mkdir(
        parents=True,
        exist_ok=True,
    )

    projects = []

    for workspace in sorted(
        PROJECTS_DIR.iterdir(),
        key=lambda item: item.stat().st_mtime,
        reverse=True,
    ):

        if not workspace.is_dir():
            continue

        # ----------------------------------------------------
        # ONLY SHOW REAL PROJECT FILES
        # ----------------------------------------------------

        files = []

        for path in workspace.rglob("*"):

            if not path.is_file():
                continue

            relative = path.relative_to(
                workspace
            )

            if not is_displayable_project_file(
                relative
            ):
                continue

            files.append(
                relative.as_posix()
            )

        zip_path = (
            PROJECTS_DIR
            / f"{workspace.name}.zip"
        )

        projects.append({

            "workspace_name":
                workspace.name,

            "project_name": re.sub(
                r"\_[0-9a-f]{8}$",
                "",
                workspace.name,
            ),

            "file_count":
                len(files),

            "files":
                sorted(files),

            "zip_available":
                zip_path.exists(),

            "project_url":
                f"/projects/"
                f"{workspace.name}",

            "zip_url": (
                f"/download-project/"
                f"{workspace.name}"
                if zip_path.exists()
                else None
            ),
        })

    return {
        "count": len(projects),
        "projects": projects,
    }


