@app.get(
    "/projects/"
    "{workspace_name}/file/"
    "{file_path:path}"
)
def view_project_file(
    workspace_name: str,
    file_path: str,
):

    path = resolve_project_file(
        workspace_name,
        file_path,
    )

    if path is None:

        raise HTTPException(
            status_code=404,
            detail=(
                "Project file not found "
                "or file type is not "
                "available for preview."
            ),
        )

    # --------------------------------------------------------
    # BASIC BINARY PROTECTION
    # --------------------------------------------------------

    try:

        sample = path.read_bytes()[
            :4096
        ]

        if b"\x00" in sample:

            raise HTTPException(
                status_code=400,
                detail=(
                    "Binary files cannot "
                    "be previewed."
                ),
            )

    except HTTPException:
        raise

    except Exception as exc:

        raise HTTPException(
            status_code=500,
            detail=str(exc),
        )

    return FileResponse(
        path=str(path),
        media_type="text/plain",
    )


