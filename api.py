# ============================================================
# DELETE PROJECT
# ============================================================

@app.delete(
    "/projects/{workspace_name}"
)
def delete_project(
    workspace_name: str,
):

    workspace = (
        resolve_project_workspace(
            workspace_name
        )
    )

    if workspace is None:

        raise HTTPException(
            status_code=404,
            detail="Project not found.",
        )

    zip_path = (
        PROJECTS_DIR
        / f"{workspace_name}.zip"
    )

    try:

        shutil.rmtree(
            workspace
        )

        if zip_path.exists():
            zip_path.unlink()

        log(
            f"🗑️ Deleted project: "
            f"{workspace_name}"
        )

        return {

            "status": "success",

            "message":
                "Project deleted successfully.",

            "workspace_name":
                workspace_name,
        }

    except Exception as exc:

        raise HTTPException(
            status_code=500,
            detail=str(exc),
        )


